    let discRevealCurrentLanguage = FALLBACK_LANGUAGE;
    function isSupported(language) { return SUPPORTED_LANGUAGES.includes(language); }

    /** Sets the active language, updates `<html lang>` and translates the static markup. */
    function setLanguage(language) {
        discRevealCurrentLanguage = isSupported(language) ? language : FALLBACK_LANGUAGE;
        document.documentElement.lang = discRevealCurrentLanguage;
        applyStaticTranslations(document);
    }

    function getLanguage() {
        return discRevealCurrentLanguage;
    }

    /** The other supported language, offered by the language switch. */
    function otherLanguage() {
        return discRevealCurrentLanguage === 'de' ? 'en' : 'de';
    }

    /** Looks up `key` in the active language and fills `{name}` placeholders from `params`. */
    function t(key, params = {}) {
        const template = dictionaries[discRevealCurrentLanguage][key] ?? dictionaries[FALLBACK_LANGUAGE][key] ?? key;
        return template.replace(/\{(\w+)\}/g, (placeholder, name) => (name in params ? String(params[name]) : placeholder));
    }

    /** Formats an integer with the digit grouping of the active language. */
    function formatNumber(value) {
        return value.toLocaleString(LOCALES[discRevealCurrentLanguage]);
    }

    /** Formats a number with exactly one decimal place in the active language. */
    function formatDecimal(value) {
        return value.toLocaleString(LOCALES[discRevealCurrentLanguage], { minimumFractionDigits: 1, maximumFractionDigits: 1 });
    }

    function formatDate(milliseconds) {
        return new Date(milliseconds).toLocaleString(LOCALES[discRevealCurrentLanguage]);
    }

    /** Translates a backend error (`{ code, detail }`) or any other thrown value. */
    function describeError(error) {
        if (error && typeof error === 'object' && typeof error.code === 'string') {
            return t(`error.${error.code}`, { detail: error.detail ?? '', seconds: error.seconds ?? '' });
        }
        return String(error);
    }

    /** Display name of a tree node; the synthetic overflow node is named per language. */
    function nodeName(node) {
        return node.overflowCount === undefined ? node.name : t('overflowItems', { count: formatNumber(node.overflowCount) });
    }

    /** Applies `data-i18n`, `data-i18n-title`, `data-i18n-aria` and `data-i18n-placeholder` inside `root`. */
    function applyStaticTranslations(root) {
        for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
        for (const element of root.querySelectorAll('[data-i18n-title]')) element.title = t(element.dataset.i18nTitle);
        for (const element of root.querySelectorAll('[data-i18n-aria]')) {
            element.setAttribute('aria-label', t(element.dataset.i18nAria));
        }
        for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
            element.placeholder = t(element.dataset.i18nPlaceholder);
        }
    }

    window.DiscRevealI18n = Object.freeze({
        setLanguage,
        getLanguage,
        otherLanguage,
        t,
        formatNumber,
        formatDecimal,
        formatDate,
        describeError,
        nodeName,
        isSupported,
    });
